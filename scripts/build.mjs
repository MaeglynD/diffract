import {cp, mkdir, rm, readdir, stat, writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {EXPERIMENTS} from '../src/experiments.js';
import {resolve, dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {packageFields} from './package-fields.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = resolve(root, 'dist');
// Only the generated dist directory in this checkout may be replaced.
if (dirname(output) !== root || output === root) throw new Error('Unsafe build directory.');
await rm(output, {recursive: true, force: true});
await mkdir(output, {recursive: true});
for (const name of ['index.html', 'src', 'vendor']) await cp(join(root, name), join(output, name), {recursive: true});
await cp(join(root, 'assets'), join(output, 'assets'), {
  recursive: true,
  filter: source => !['assets/fields','assets/spectra'].some(path=>resolve(source)===resolve(root,path))
});
const spectrumAssets={};await mkdir(join(output,'assets/spectra'),{recursive:true});
for(const id of [...EXPERIMENTS.map(e=>e.id),'double-right']){
 const bytes=await readFile(join(root,'assets/spectra',id+'.spectrum.gz')),sha256=createHash('sha256').update(bytes).digest('hex'),file=sha256+'.spectrum';
 await writeFile(join(output,'assets/spectra',file),bytes);spectrumAssets[id]={file,bytes:bytes.length,sha256};
}
const spectrumModule=await readFile(join(root,'src/spectrum-assets.js'),'utf8');
await writeFile(join(output,'src/spectrum-assets.js'),spectrumModule.replace('export const spectrumAssets = {};',`export const spectrumAssets = ${JSON.stringify(spectrumAssets)};`));
const binaryAssets={};await mkdir(join(output,'assets/binary'),{recursive:true});
for(const path of [...(await readdir(join(root,'assets/elements'))).filter(n=>n.endsWith('.relief')).map(n=>'assets/elements/'+n),'assets/models/bunny.mesh']){
 const raw=await readFile(join(root,path)),bytes=gzipSync(raw,{level:9}),sha256=createHash('sha256').update(raw).digest('hex'),file=createHash('sha256').update(bytes).digest('hex')+'.geometry';await writeFile(join(output,'assets/binary',file),bytes);binaryAssets[path]={file,bytes:bytes.length,sha256};
}
const binaryModule=await readFile(join(root,'src/binary-assets.js'),'utf8');await writeFile(join(output,'src/binary-assets.js'),binaryModule.replace('export const binaryAssets = {};',`export const binaryAssets = ${JSON.stringify(binaryAssets)};`));
const manifest = await packageFields(join(root, 'assets/fields'), join(output, 'assets/fields'));
await writeFile(join(output, 'src/field-assets.js'), `// Generated by scripts/build.mjs.\nexport const fieldAssets = ${JSON.stringify(manifest)};\n`);
await cp(join(root, '_headers'), join(output, '_headers'));
let count = 0, largest = 0;
async function checkDirectory(path) {
  for (const entry of await readdir(path, {withFileTypes: true})) {
    const file = join(path, entry.name);
    if (entry.isDirectory()) await checkDirectory(file);
    else {
      const {size} = await stat(file);
      if (size > 25 * 1024 * 1024) throw new Error(`${file} exceeds Cloudflare's 25 MiB asset limit.`);
      count++;
      largest = Math.max(largest, size);
    }
  }
}
await checkDirectory(output);
console.log(`Built static app: ${count} files, largest ${(largest / 1024 ** 2).toFixed(1)} MiB; ${Object.keys(manifest).length} losslessly packaged volumes.`);
