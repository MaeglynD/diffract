import {cp, mkdir, rm, readdir, stat, writeFile} from 'node:fs/promises';
import {resolve, dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {packageFields} from './package-fields.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = resolve(root, 'dist');
// Only the generated dist directory in this checkout may be replaced.
if (dirname(output) !== root || output === root) throw new Error('Unsafe build directory.');
await rm(output, {recursive: true, force: true});
await mkdir(output, {recursive: true});
for (const name of ['index.html', 'src', 'vendor']) await cp(join(root, name), join(output, name), {recursive: true});
await cp(join(root, 'assets'), join(output, 'assets'), {
  recursive: true,
  filter: source => resolve(source) !== resolve(root, 'assets/fields')
});
const manifest = await packageFields(join(root, 'assets/fields'), join(output, 'assets/fields'));
await writeFile(join(output, 'src/field-assets.js'), `// Generated by scripts/build.mjs.\nexport const fieldAssets = ${JSON.stringify(manifest)};\n`);
await cp(join(root, '_headers'), join(output, '_headers'));
let count = 0, largest = 0;
async function checkDirectory(path) {
  for (const entry of await readdir(path, {withFileTypes: true})) {
    const file = join(path, entry.name);
    if (entry.isDirectory()) await checkDirectory(file);
    else {
      const {size} = await stat(file);
      if (size > 25 * 1024 * 1024) throw new Error(`${file} exceeds Cloudflare's 25 MiB asset limit.`);
      count++;
      largest = Math.max(largest, size);
    }
  }
}
await checkDirectory(output);
console.log(`Built static app: ${count} files, largest ${(largest / 1024 ** 2).toFixed(1)} MiB; ${Object.keys(manifest).length} losslessly packaged volumes.`);
